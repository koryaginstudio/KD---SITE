export function translateDynamicText(value: string) {
  const normalized = value.trim();
  const exact = staticTranslations[normalized];
  if (exact) return value.replace(normalized, exact);

  const patterns: Array<[RegExp, (...parts: string[]) => string]> = [
    [/^Вопрос (\d+) из (\d+)$/, (_all, current, total) => `Question ${current} of ${total}`],
    [/^Отзыв (\d+) из (\d+)$/, (_all, current, total) => `Review ${current} of ${total}`],
    [/^Фото (\d+) из (\d+)$/, (_all, current, total) => `Image ${current} of ${total}`],
    [/^Проект (\d+): (.+)$/, (_all, number, title) => `Project ${number}: ${title}`],
    [/^Открыть кейс: (.+)$/, (_all, title) => `Open case: ${title}`],
    [/^Этап (.+)$/, (_all, step) => `Step ${step}`],
  ];

  for (const [pattern, replacement] of patterns) {
    const match = normalized.match(pattern);
    if (match) return value.replace(normalized, replacement(...match));
  }
  return value;
}
